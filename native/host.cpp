// The native EVG Player: the same PlayerApp (PlayerApp.rgr, compiled to C++
// by Ranger) in a window that is the shape of the skin.
//
// This file is web/main.js for a desktop. It owns what an operating system
// has and Ranger does not — the window, the pointer, the files, the sound —
// and asks the app everything else: what is under the pointer (`hitId`),
// what a press means (`press`, which answers with a command for this file),
// and what to draw (`displayListJson`, painted by painter.cpp).
//
//   evg-player [--demo] [--frames N --shot out.pam] [--press id] [music files or folders…]
//
// --demo drives the visualiser with made-up levels, --frames N quits after N
// frames, --shot writes the last frame (RGBA, alpha included) as a PAM image,
// --press <id> presses a button at start (viz, skin, next…). EVGP_DEBUG=1
// reports the shape.

#include <SDL.h>

#include <chrono>
#include <cmath>
#include <cstdio>
#include <filesystem>
#include <fstream>

#include "PlayerApp.cpp"  // generated by Ranger from ../PlayerApp.rgr
#include "assets.h"       // generated: player.css and the effects' GLSL
#include "audio.h"
#include "gl.h"
#include "painter.h"
